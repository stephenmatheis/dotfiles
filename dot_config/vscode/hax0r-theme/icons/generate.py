# Builds icon-theme.template.json from VS Code's built-in Seti icon theme, recolored the way
# nvim's mini.icons is in colors/hax0r.lua: gray icons in fg, every other icon in normal.
# `hax0r build` then fills in those two colors for each theme. Rerun this after a VS Code update
# to pick up new Seti icons, then run `hax0r build`:
#   python3 ~/.config/vscode/hax0r-theme/icons/generate.py
import colorsys, json, os, struct, sys, zlib

seti = sys.argv[1] if len(sys.argv) > 1 else \
    '/Applications/Visual Studio Code.app/Contents/Resources/app/extensions/theme-seti/icons'
here = os.path.dirname(os.path.abspath(__file__))
theme = json.load(open(os.path.join(seti, 'vs-seti-icon-theme.json')))


def recolor(color):
    r, g, b = (int(color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    gray = colorsys.rgb_to_hls(r, g, b)[2] < 0.2
    return '{{fg}}' if gray else '{{normal}}'


def checksum(data):
    data += b'\0' * (-len(data) % 4)
    return sum(struct.unpack(f'>{len(data) // 4}I', data)) & 0xFFFFFFFF


# Unwrap WOFF into a plain TrueType/OpenType font: VS Code only loads .ttf/.otf, not .woff,
# from extensions outside ~/.vscode/extensions, and this one lives in ~/.config.
def woff_to_sfnt(woff):
    signature, flavor, _, num_tables = struct.unpack('>4s4sIH', woff[:14])
    assert signature == b'wOFF', 'not a WOFF 1.0 font'
    tables = []
    for i in range(num_tables):
        tag, offset, comp_len, orig_len, orig_sum = struct.unpack('>4sIIII', woff[44 + 20 * i:64 + 20 * i])
        data = woff[offset:offset + comp_len]
        if comp_len < orig_len:
            data = zlib.decompress(data)
        assert len(data) == orig_len and (tag == b'head' or checksum(data) == orig_sum), tag
        tables.append((tag, orig_sum, data))
    entry_selector = num_tables.bit_length() - 1
    search_range = 16 << entry_selector
    out = struct.pack('>4sHHHH', flavor, num_tables, search_range, entry_selector, num_tables * 16 - search_range)
    offset = 12 + 16 * num_tables
    directory, body, head = b'', b'', None
    for tag, orig_sum, data in tables:
        if tag == b'head':
            head = offset + len(body)
        directory += struct.pack('>4sIII', tag, orig_sum, offset + len(body), len(data))
        body += data + b'\0' * (-len(data) % 4)
    font = bytearray(out + directory + body)
    # head's checkSumAdjustment makes the whole file sum to 0xB1B0AFBA
    font[head + 8:head + 12] = bytes(4)
    font[head + 8:head + 12] = struct.pack('>I', (0xB1B0AFBA - checksum(bytes(font))) & 0xFFFFFFFF)
    return bytes(font), ('.otf', 'opentype') if flavor == b'OTTO' else ('.ttf', 'truetype')


for icon in theme['iconDefinitions'].values():
    if 'fontColor' in icon:
        icon['fontColor'] = recolor(icon['fontColor'])

font, (ext, fmt) = woff_to_sfnt(open(os.path.join(seti, 'seti.woff'), 'rb').read())
with open(os.path.join(here, 'seti' + ext), 'wb') as f:
    f.write(font)
theme['fonts'][0]['src'] = [{'path': './seti' + ext, 'format': fmt}]

theme['information_for_contributors'] = [
    'Generated by generate.py and ~/.config/hax0r/generate.lua from VS Code\'s built-in Seti icon theme; don\'t edit by hand.',
    'Seti UI is MIT licensed, see SETI-LICENSE.txt. "version" is the seti-ui commit it came from.',
]
with open(os.path.join(here, 'icon-theme.template.json'), 'w') as f:
    json.dump(theme, f, indent='\t')
    f.write('\n')
